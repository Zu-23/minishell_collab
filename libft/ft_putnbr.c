#include "libft.h"

void	ft_putnbr(int n)
{
	long	ln;

	ln = n;
	if (n < 0)
	{
		ft_putchar('-');
		ln *= -1;
	}
	if (ln > 9)
		ft_putnbr(ln / 10);
	ft_putchar((ln % 10) + 48);
}
