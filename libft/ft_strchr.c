#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	if (*s == (char)c)
		return ((char *)s);
	else if (*s)
		while (*s++)
			if ((char)*s == (char)c)
				return ((char *)(s));
	return (NULL);
}
